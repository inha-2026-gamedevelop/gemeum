using UnityEngine;

namespace Geumeum.Common
{
    /// <summary>
    /// 락온과 조준 보정이 겨누는 지점. <b>루트가 아니라 조준점을 향한다</b> -
    /// 발밑을 겨누면 화살이 땅에 박히고, 캡슐 중심을 겨누면 배를 쏜다.
    /// 전투가 AI의 구체 클래스를 참조하지 않도록 계약만 Common에 둔다
    /// </summary>
    /// <remarks>
    /// <b>부위마다 하나씩 붙인다.</b> 보스는 몸통과 꼬리 세 덩이가 각각 별개의 락온 대상이므로
    /// 콜라이더마다 자기 조준점을 들고 있어야 한다 - 그래야 보스 패턴 계약 8.2의
    /// "그로기 진입 시 표식 꼬리로 자동 전환"이 <b>실제로 그 꼬리를 향한다</b>.
    /// 하나만 붙여 두면 꼬리를 잠가도 카메라와 화살은 몸통을 본다.
    ///
    /// 구현 기준값 - 잡귀는 캡슐 중심보다 위인 가슴(2m 캡슐 기준 로컬 Y 1.1m),
    /// 보스는 몸통 anchor + 부위별 anchor.
    /// <b>이 계약이 없는 임시 대상은 호출부가 콜라이더의 <c>bounds.center</c>로 폴백한다</b> -
    /// 폴백 규칙을 호출부마다 다르게 만들지 않기 위해 여기 적어 둔다.
    ///
    /// 조준점은 <b>표현이 아니라 판정에 쓰인다</b>(화살 유도가 서버 판정이다).
    /// 따라서 서버와 클라이언트가 같은 값을 내야 하고, 화면 전용 값을 섞으면 안 된다
    /// → 카메라와 락온 설계 3.0 · 12장, 화살 조준 보정 설계 5.2
    /// </remarks>
    public interface IAimAssistTarget
    {
        /// <summary> 겨눌 월드 좌표. 매 프레임 조회되므로 여기서 무거운 계산을 하지 않는다 </summary>
        Vector3 AimPoint { get; }
    }
}
